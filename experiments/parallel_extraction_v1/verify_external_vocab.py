"""Extract and verify candidate vocabulary from the user-supplied AI-generated
reference file (resources/filipino_kapampangan_parallel_corpus.md).

Per user decision (2026-08-26): the document overlaps extensively (verbatim)
with this experiment's own pldpair_001-039, almost certainly because it was
generated by an LLM working from this session's own prior output -- so that
overlap is not independent corroboration. Only non-overlapping items are
treated as new candidates, and every one of those is cross-checked against
this project's existing page-cited attestation evidence
(experiments/internet_root_reconciliation_v1/reports/word-evidence.csv and
experiments/source_adjudicated_v2/resources/training-lexicon.json) before
any acceptance decision is made. This script does the mechanical extraction
and lookup only -- it does not decide accept/reject; that judgment is made
separately (see reports/external-vocab-verification.md) and only accepted
items are added to build_matched_pairs.py.
"""

from __future__ import annotations

import csv
import json
import re
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent
MD_PATH = BASE_DIR / "resources" / "filipino_kapampangan_parallel_corpus.md"
WORD_EVIDENCE_PATH = (
    BASE_DIR.parent / "internet_root_reconciliation_v1" / "reports" / "word-evidence.csv"
)
LEXICON_PATH = BASE_DIR.parent / "source_adjudicated_v2" / "resources" / "training-lexicon.json"
EXISTING_PAIRS_PATH = BASE_DIR / "reports" / "matched-pairs.csv"
OUTPUT_PATH = BASE_DIR / "reports" / "external-vocab-candidates.csv"

TABLE_ROW_RE = re.compile(r"^\|\s*(\d+)\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|$")

# Every table section (1-214). Do NOT assume a whole section is duplicate by
# range -- some items even within Greetings/Interrogatives/CommonExpressions/
# Proverbs turned out not to be among pldpair_001-039 (e.g. item 2 "Good
# noon" has no match in the existing pair set). Let the normalize()-based
# text match against matched-pairs.csv decide duplicate status per item,
# not the section it sits in.
NEW_CANDIDATE_RANGES = [
    (1, 18, "Greetings and Courtesies"),
    (19, 33, "Interrogatives & Question Words"),
    (34, 53, "Pronouns & Demonstratives"),
    (54, 81, "Numbers, Time & Calendar"),
    (82, 100, "Family & Human Relations"),
    (101, 120, "Body Parts & Health"),
    (121, 137, "Food, Cooking & Dining"),
    (138, 157, "Nature, Weather & Environment"),
    (158, 179, "Common Verbs & Actions"),
    (180, 201, "Adjectives & Descriptors"),
    (202, 210, "Common Conversational Expressions"),
    (211, 214, "Proverbs & Sayings"),
]


def normalize(text: str) -> str:
    text = text.strip().lower()
    text = re.sub(r"[.!?]+$", "", text)
    text = re.sub(r"\s+", " ", text)
    return text


def load_md_rows() -> list[dict]:
    rows = []
    for line in MD_PATH.read_text(encoding="utf-8").splitlines():
        m = TABLE_ROW_RE.match(line.strip())
        if not m:
            continue
        num, fil, pam, eng = m.groups()
        if fil == "Filipino (Tagalog)" or fil.startswith("---"):
            continue
        rows.append({"num": int(num), "fil": fil, "pam": pam, "eng": eng})
    return rows


def load_existing_pair_texts() -> set[str]:
    texts = set()
    with EXISTING_PAIRS_PATH.open(encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            texts.add(normalize(row["pam_text"]))
            texts.add(normalize(row["fil_text"]))
    return texts


def load_word_evidence() -> dict[str, dict]:
    index = {}
    with WORD_EVIDENCE_PATH.open(encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            index[row["comparison_key"]] = row
    return index


def load_lexicon_roots() -> set[str]:
    with LEXICON_PATH.open(encoding="utf-8") as f:
        lex = json.load(f)
    return {r["comparison_key"] for r in lex["roots"]}


def pam_tokens(pam_field: str) -> list[str]:
    # PAM cells often carry alternates like "Aku" or "Nucarin? / Pukarin?" or
    # "Apu a lalaki" -- split on '/' for alternates, then on whitespace for
    # individual word tokens within each alternate.
    alternates = [a.strip() for a in pam_field.split("/")]
    tokens = []
    for alt in alternates:
        alt_clean = re.sub(r"[.,;:!?()]", " ", alt)
        for tok in alt_clean.split():
            key = tok.strip().lower()
            key = re.sub(r"[^a-záéíóúñü'-]", "", key)
            if key:
                tokens.append(key)
    return tokens


def main() -> None:
    md_rows = load_md_rows()
    existing = load_existing_pair_texts()
    evidence = load_word_evidence()
    lexicon_roots = load_lexicon_roots()

    out_rows = []
    for lo, hi, section in NEW_CANDIDATE_RANGES:
        for row in md_rows:
            if not (lo <= row["num"] <= hi):
                continue
            pam_norm = normalize(row["pam"])
            fil_norm = normalize(row["fil"])
            is_duplicate = pam_norm in existing or fil_norm in existing
            toks = pam_tokens(row["pam"])
            tok_status = []
            for tok in toks:
                in_evidence = tok in evidence
                in_lexicon = tok in lexicon_roots
                decision = evidence[tok]["decision"] if in_evidence else ""
                sources = evidence[tok]["whole_form_sources"] if in_evidence else ""
                tok_status.append(
                    {
                        "token": tok,
                        "in_word_evidence": in_evidence,
                        "in_lexicon_roots": in_lexicon,
                        "decision": decision,
                        "has_dictionary_source": bool(sources),
                    }
                )
            any_attested = any(t["in_word_evidence"] or t["in_lexicon_roots"] for t in tok_status)
            all_attested = all(t["in_word_evidence"] or t["in_lexicon_roots"] for t in tok_status) if tok_status else False
            out_rows.append(
                {
                    "item_num": row["num"],
                    "section": section,
                    "fil": row["fil"],
                    "pam": row["pam"],
                    "eng": row["eng"],
                    "is_duplicate_of_existing_pair": is_duplicate,
                    "pam_tokens_checked": ", ".join(t["token"] for t in tok_status),
                    "all_tokens_attested": all_attested,
                    "any_token_attested": any_attested,
                    "token_detail": "; ".join(
                        f"{t['token']}={'attested' if (t['in_word_evidence'] or t['in_lexicon_roots']) else 'NOT_FOUND'}"
                        for t in tok_status
                    ),
                }
            )

    fieldnames = [
        "item_num",
        "section",
        "fil",
        "pam",
        "eng",
        "is_duplicate_of_existing_pair",
        "pam_tokens_checked",
        "all_tokens_attested",
        "any_token_attested",
        "token_detail",
    ]
    with OUTPUT_PATH.open("w", encoding="utf-8", newline="\n") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(out_rows)

    total = len(out_rows)
    dup = sum(1 for r in out_rows if r["is_duplicate_of_existing_pair"])
    all_attested = sum(1 for r in out_rows if r["all_tokens_attested"] and not r["is_duplicate_of_existing_pair"])
    partial = sum(
        1
        for r in out_rows
        if r["any_token_attested"] and not r["all_tokens_attested"] and not r["is_duplicate_of_existing_pair"]
    )
    none_attested = sum(
        1 for r in out_rows if not r["any_token_attested"] and not r["is_duplicate_of_existing_pair"]
    )
    print(f"total candidate rows: {total}")
    print(f"already duplicate of existing pairs (skipped): {dup}")
    print(f"new, all PAM tokens attested: {all_attested}")
    print(f"new, some PAM tokens attested: {partial}")
    print(f"new, no PAM tokens attested: {none_attested}")


if __name__ == "__main__":
    main()
